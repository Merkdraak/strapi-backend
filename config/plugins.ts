import type { Core } from '@strapi/strapi';

const allowedMediaTypes = [
  'image/*',
  'video/*',
  'audio/*',
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.*',
  'text/plain',
  'text/csv',
];

const deniedTypes = [
  'image/svg+xml',
  'application/vnd.microsoft.portable-executable',
  'application/x-msdownload',
  'application/x-msdos-program',
  'application/x-executable',
  'application/x-dosexec',
  'application/x-sh',
  'text/x-shellscript',
  'application/x-mach-binary',
];

const config = ({ env }: Core.Config.Shared.ConfigParams): Core.Config.Plugin => ({
  'users-permissions': {
    config: {
      jwtManagement: 'refresh',
      sessions: {
        httpOnly: true,
      },
    },
  },
  upload: {
    config: {
      /**
       * Responsive derivatives keep the source mime (PNG stays PNG). That is why many
       * large_/medium_ files on production are heavy photo PNGs.
       *
       * Safe local policy (no live media rewrite):
       * - Prefer uploading JPEG/WebP for photos; PNG only when transparency is required.
       * - Prefer sources ≥1600px wide for cases/heroes (retina headroom).
       * - Existing library files are NOT regenerated by this config — see
       *   audits/strapi-media-migration-plan.json in merkdraak-frontend for the
       *   separate CMS migration steps.
       */
      sizeOptimization: true,
      responsiveDimensions: true,
      // Explicit breakpoints (Strapi defaults) — changes apply to NEW uploads only.
      breakpoints: {
        large: 1000,
        medium: 750,
        small: 500,
      },
      sharp: {
        // Lower peak memory during derivative generation on small hosts.
        cache: false,
        concurrency: 1,
      },
      security: {
        allowedTypes: allowedMediaTypes,
        deniedTypes,
      },
    },
  },
  email: {
    config: {
      provider: 'nodemailer',
      providerOptions: {
        host: env('SMTP_HOST', 'smtp.gmail.com'),
        port: env.int('SMTP_PORT', 587),
        secure: env.bool('SMTP_SECURE', false),
        auth: {
          user: env('SMTP_USERNAME'),
          pass: env('SMTP_PASSWORD'),
        },
      },
      settings: {
        defaultFrom: env('SMTP_DEFAULT_FROM', 'noreply@merkdraak.nl'),
        defaultReplyTo: env('SMTP_DEFAULT_REPLY_TO', 'info@merkdraak.nl'),
      },
    },
  },
});

export default config;
